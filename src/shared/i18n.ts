export const MESSAGES: Record<UiLanguage, Record<MessageKey, string>> = { en, 'pt-BR': ptBR };

export type Vars = Record<string, string | number>;
export type Translate = (key: MessageKey, vars?: Vars) => string;

/** Builds the `t()` used across the renderer. Missing keys fall back to English. */
export function translator(language: UiLanguage): Translate {
  const table = MESSAGES[language] ?? MESSAGES.en;
  return (key, vars) => {
    const template = table[key] ?? MESSAGES.en[key] ?? key;
    if (!vars) return template;
    return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
      name in vars ? String(vars[name]) : whole,
    );
  };
}

/** Maps whatever Electron reports as the system locale onto a UI language. */
export function detectLanguage(systemLocale: string): UiLanguage {
  return systemLocale.toLowerCase().startsWith('pt') ? 'pt-BR' : 'en';
}
